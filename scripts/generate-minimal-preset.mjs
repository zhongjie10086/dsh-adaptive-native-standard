import assert from 'node:assert/strict'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const sourcePath = join(root, 'preset', 'agent.cordis.yml')
const targetPath = join(root, 'preset-minimal', 'agent.cordis.yml')

function replaceOnce(input, search, replacement, label) {
  const first = input.indexOf(search)
  assert.notEqual(first, -1, `minimal preset generator: missing ${label}`)
  assert.equal(input.indexOf(search, first + search.length), -1, `minimal preset generator: duplicate ${label}`)
  return `${input.slice(0, first)}${replacement}${input.slice(first + search.length)}`
}

export function generateMinimalComposition(standardSource) {
  let output = standardSource.replace(/\r\n/g, '\n')
  const bootstrapMarker = '# ── bootstrap (must stay FIRST) ─────────────────────────────────────────────\n'
  const markerAt = output.indexOf(bootstrapMarker)
  assert.ok(markerAt > 0, 'minimal preset generator: bootstrap marker missing')
  output = [
    '# GENERATED by scripts/generate-minimal-preset.mjs from preset/agent.cordis.yml.',
    '# Do not edit this file directly; edit the Standard composition or generator.',
    '#',
    '# Adaptive Native Minimal keeps a compact Minimal-shaped first model request:',
    '# one base persona plus the selected Adaptive task persona, no runtime/persistent',
    '# injected context, and only read + dev_tool_search. Weak tasks may also receive',
    '# one near-field guide. The first durable tool call or assistant message promotes',
    '# the session permanently; request #2 restores essential runtime context and',
    '# the Windows core tools while heavier capabilities stay on demand.',
    '',
    output.slice(markerAt),
  ].join('\n')

  output = replaceOnce(output,
    [
      '# This row deliberately sits before every other row so its pre-step filter is',
      '# deterministic. Request #1 keeps Standard\'s assembled prompt and context but',
      '# replaces only the deployment persona with Minimal and exposes six native',
      '# Windows work tools. After the first durable tool call or assistant message,',
      '# the catalog adds small discovery/routing controls; heavier tools remain one',
      '# dev_tool_search call away. After compaction the same six-tool work surface is',
      '# restored until a new durable promotion signal appears.',
    ].join('\n'),
    [
      '# Request #1 is a compact Minimal-shaped phase: its prompt contains the base',
      '# persona plus one selected Adaptive task persona, its injected contexts are',
      '# empty, and its catalog is exactly read + dev_tool_search. Weak tasks may also',
      '# receive one near-field guide. The first durable tool call or assistant message',
      '# promotes the session. Promotion is session-scoped and survives compaction,',
      '# resume, reload, and Controller restarts.',
    ].join('\n'),
    'bootstrap explanation')

  output = replaceOnce(output,
    [
      '# The selected base persona remains an ordinary, non-complete section. The',
      '# router replaces only this deployment persona with Minimal for request #1,',
      '# then restores it and appends adaptive routing after promotion.',
    ].join('\n'),
    [
      '# This fallback persona lets the composition fail open. During normal routing,',
      '# request #1 replaces every system section with the Minimal base plus the',
      '# selected Adaptive task persona;',
      '# promoted requests keep a Minimal base and only conditional tool rules.',
    ].join('\n'),
    'identity explanation')

  output = replaceOnce(output,
    '    bootstrapTools: [pwsh, read, write, edit, glob, grep]\n    residentTools: [dev_tool_search, skill_search, skill_load, dev_adaptive_status, dev_adaptive_mode]\n    promoteOn: either\n    suppressedContextSources: []',
    '    bootstrapTools: [read, dev_tool_search]\n    residentTools: [pwsh, write, edit, glob, grep, dev_tool_search]\n    promoteOn: either\n    resetOnCompaction: false\n    suppressedContextSources: [skill-catalog, agent-instructions]',
    'bootstrap tool policy')
  output = replaceOnce(output,
    '    compactionTools: [pwsh, read, write, edit, glob, grep]',
    '    compactionTools: [read, dev_tool_search]',
    'compaction tool policy')
  output = replaceOnce(output,
    '    reasoningStyle: we-need',
    '    reasoningStyle: native',
    'Minimal native reasoning policy')
  output = replaceOnce(output,
    '# The optional we-need style starts only after the anchor is durable.',
    '# Minimal keeps Adaptive task personas and Weak near-field guidance from request #1,\n# but uses native reasoning without the we-need style or reminder.',
    'Minimal routing explanation')
  output = replaceOnce(output,
    '    bootstrapAnchor: minimal-persona',
    '    bootstrapAnchor: minimal-first\n    resetOnCompaction: false',
    'router bootstrap anchor')
  output = replaceOnce(output,
    '- id: instruction-hint\n  name: ./instruction-hint.mjs\n  config:\n    promoteOn: either',
    '- id: instruction-hint\n  name: ./instruction-hint.mjs\n  config:\n    promoteOn: either\n    resetOnCompaction: false',
    'instruction hint policy')

  const editorStart = output.indexOf('# The Minimal preset\'s second tool: `str_replace_editor`')
  const jobsMarker = '# ── background jobs ────────────────────────────────────────────────────────\n'
  const editorEnd = output.indexOf(jobsMarker, editorStart)
  assert.ok(editorStart >= 0 && editorEnd > editorStart, 'minimal preset generator: editor block markers missing')
  output = `${output.slice(0, editorStart)}${jobsMarker}${output.slice(editorEnd + jobsMarker.length)}`

  assert.match(output, /bootstrapTools: \[read, dev_tool_search\]/)
  assert.match(output, /residentTools: \[pwsh, write, edit, glob, grep, dev_tool_search\]/)
  assert.match(output, /bootstrapAnchor: minimal-first/)
  assert.match(output, /reasoningStyle: native/)
  assert.match(output, /nearFieldGuidance: true/)
  assert.equal((output.match(/resetOnCompaction: false/g) ?? []).length, 3)
  assert.doesNotMatch(output, /str-replace-editor|tool-str-replace-editor|bootstrapTools: \[[^\]]*(?:pwsh|write|edit|glob|grep)/)
  return output.endsWith('\n') ? output : `${output}\n`
}

const generated = generateMinimalComposition(readFileSync(sourcePath, 'utf8'))
if (process.argv.includes('--check')) {
  assert.equal(readFileSync(targetPath, 'utf8').replace(/\r\n/g, '\n'), generated,
    'preset-minimal/agent.cordis.yml is stale; run npm run generate:minimal')
  console.log('minimal preset generation: up to date')
} else {
  mkdirSync(dirname(targetPath), { recursive: true })
  writeFileSync(targetPath, generated, 'utf8')
  console.log(`minimal preset generation: wrote ${targetPath}`)
}
